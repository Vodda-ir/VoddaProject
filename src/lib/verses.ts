/** شاخص روز (۰ تا ۳۶۵) بر پایهٔ تاریخ محلی — بدون وابستگی به Next/React. */
export function dayOfYearIndex(now: Date = new Date()): number {
  const start = new Date(now.getFullYear(), 0, 0);
  return Math.floor((now.getTime() - start.getTime()) / 86_400_000);
}

/** آیه/حدیث امروز. */
export function verseOfDay(now: Date = new Date()): DailyVerse {
  return DAILY_VERSES[dayOfYearIndex(now) % DAILY_VERSES.length];
}
