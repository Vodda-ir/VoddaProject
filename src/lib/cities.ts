/** همهٔ نام شهرها — مرتب‌شده با ترتیب فارسی. */
export function allCityNames(): string[] {
  return CITY_COORDS.map((row) => row[0]).sort((a, b) => a.localeCompare(b, "fa"));
}

/* ───────── نرمال‌سازی متن فارسی برای جستجو (ی/ک/آ/نیم‌فاصله) ───────── */

export function normalizeFa(text: string): string {
  return text
    .replace(/[\u064A\u0649]/g, "\u06CC") // ي عربی و ۀ پایانی → ی فارسی
    .replace(/\u0643/g, "\u06A9") // ك عربی → ک فارسی
    .replace(/[\u0623\u0625\u0622]/g, "\u0627") // أ/إ/آ → ا
    .replace(/\u0629/g, "\u0647") // ة → ه
    .replace(/[\u200C\u200E\u200F]/g, "") // نیم‌فاصله و نشانه‌های جهت
    .replace(/\s+/g, "") // فاصله‌ها هم حذف — «خرم اباد» هم «خرم‌آباد» را پیدا کند
    .trim();
}

/** فیلتر جستجوی شهر — نرمال‌شده و مرتب با ترتیب فارسی. */
export function searchCityNames(query: string, pool?: string[]): string[] {
  const source = pool ?? allCityNames();
  const needle = normalizeFa(query);
  if (!needle) return source;
  return source
    .filter((name) => normalizeFa(name).includes(needle))
    .sort((a, b) => a.localeCompare(b, "fa"));
}

/* ───────── نزدیک‌ترین شهر از مختصات (haversine) ───────── */

const EARTH_RADIUS_KM = 6371;
/** حداکثر فاصلهٔ منطقی از مرکز یک شهر — دورتر از آن یعنی خارج پوشش شهرها. */
const MAX_CITY_RADIUS_KM = 150;

function haversineKm(lat1: number, lon1: number, lat2: number, lon2: number): number {
  const toRad = (value: number) => (value * Math.PI) / 180;
  const dLat = toRad(lat2 - lat1);
  const dLon = toRad(lon2 - lon1);
  const a =
    Math.sin(dLat / 2) ** 2 +
    Math.cos(toRad(lat1)) * Math.cos(toRad(lat2)) * Math.sin(dLon / 2) ** 2;
  return 2 * EARTH_RADIUS_KM * Math.asin(Math.min(1, Math.sqrt(a)));
}

/** نزدیک‌ترین شهر ایران به مختصات؛ خارج از شعاع ۱۵۰km → null (به پروفایل برمی‌گردیم). */
export function nearestCity(lat: number, lon: number): string | null {
  if (!Number.isFinite(lat) || !Number.isFinite(lon)) return null;
  let best: string | null = null;
  let bestKm = Number.POSITIVE_INFINITY;
  for (const [name, cityLat, cityLon] of CITY_COORDS) {
    const km = haversineKm(lat, lon, cityLat, cityLon);
    if (km < bestKm) {
      bestKm = km;
      best = name;
    }
  }
  return bestKm <= MAX_CITY_RADIUS_KM ? best : null;
}
